needs_cxx = pytest.mark.skipif(find_cxx() is None, reason="no C++ compiler available")

VALID_EXAMPLES = sorted(p.name for p in EXAMPLES_DIR.glob("*.cb") if not p.name.startswith("error_"))


def cpp_for(source: str, optimized: bool = True) -> str:
    code = generate_tac(analyzed(source))
    if optimized:
        code, _ = optimize(code)
    cpp, structured = generate_cpp(code)
    assert structured
    return cpp


def test_program_skeleton():
    cpp = cpp_for('print("hi")')
    assert cpp.startswith("// Generated by CodeBridge")
    for needed in ("#include <iostream>", "#include <string>", "int main() {",
                   "std::cout << std::boolalpha;", "return 0;"):
        assert needed in cpp
    assert 'std::cout << "hi\\n";' in cpp


def test_print_merges_adjacent_literal_text():
    cpp = cpp_for('let n = 3\nwhile n > 0 { print("n is", n, "now")\nn = n - 1 }\nprint()')
    assert 'std::cout << "n is " << n << " now\\n";' in cpp
    assert 'std::cout << "\\n";' in cpp


def test_type_mapping_and_inline_declarations():
    cpp = cpp_for('let i = 1\nlet f = 2.5\nlet s = "x"\nlet b = true\nprint(i, f, s, b)')
    for decl in ("long long i = 1;", "double f = 2.5;", 'std::string s = "x";', "bool b = true;"):
        assert decl in cpp


def test_variables_first_assigned_in_blocks_are_hoisted():
    cpp = cpp_for("let n = 0\nwhile n < 3 { let sq = n * n\nprint(sq)\nn = n + 1 }")
    assert "long long sq = 0;" in cpp.split("long long n = 0;")[0]
    assert "while (n < 3) {" in cpp
    assert "sq = n * n;" in cpp


def test_structured_control_flow():
    cpp = cpp_for("let x = 3\nwhile x > 0 {\nif x == 2 { print(\"two\") } else if x == 1 { print(1) }"
                  " else { print(x) }\nx = x - 1 }")
    assert "goto" not in cpp
    assert "if (x == 2) {" in cpp
    assert "} else if (x == 1) {" in cpp
    assert "} else {" in cpp


def test_expressions_are_rebuilt_with_correct_parentheses():
    cpp = cpp_for("let a = 1\nlet b = 2\nwhile a < 9 { a = (a + b) * (a - b) - -b / 2\n"
                  "print(a - (b - 1), not (a < b), (a < b) == (b < a)) }")
    assert "a = (a + b) * (a - b) - -b / 2;" in cpp
    assert "a - (b - 1)" in cpp
    assert "!(a < b)" in cpp
    assert "(a < b) == (b < a)" in cpp


def test_conversion_and_string_concatenation():
    cpp = cpp_for('let i = 3\nlet s = "n="\nwhile i > 0 { print(s + "x", i * 0.5)\ni = i - 1 }')
    assert "static_cast<double>(i) * 0.5" in cpp
    assert 's + "x"' in cpp


def test_string_literal_operand_is_wrapped():
    code = [Copy(Var("s", Type.STRING), Const("b", Type.STRING)),
            BinOp(Var("t1", Type.STRING, temp=True), "+", Const("a", Type.STRING), Var("s", Type.STRING)),
            Print((Var("t1", Type.STRING, temp=True),))]
    cpp, _ = generate_cpp(code)
    assert 'std::string("a") + s' in cpp


def test_string_escaping():
    assert cpp_string('a"b\\c\nd\te\x01') == '"a\\"b\\\\c\\nd\\te\\001"'
    assert cpp_string("héllo ✓") == '"héllo ✓"'


def test_extreme_integer_constant():
    code = [Print((Const(-(2**63), Type.INT), Const(-5, Type.INT)))]
    cpp, _ = generate_cpp(code)
    assert "(-9223372036854775807LL - 1)" in cpp


def test_unstructured_tac_falls_back_to_goto():
    x = Var("x", Type.INT)
    code = [Copy(x, Const(0, Type.INT)), Label("L1"), Print((x,)),
            Copy(x, Const(1, Type.INT)), IfFalse(Const(True, Type.BOOL), "L2"),
            Goto("L3"), Label("L2"), Goto("L1"), Label("L3")]
    cpp, structured = generate_cpp(code)
    assert structured is False
    assert "goto" in cpp and "long long x = 0;" in cpp


def test_cpp_follows_optimized_tac():
    result = compile_source("let a = 6 * 7\nprint(a)")
    assert result.success
    assert "long long a = 42;" in result.cpp and "std::cout << 42" in result.cpp


# ------------------------------------------------- real C++ compilation
@needs_cxx
@pytest.mark.parametrize("name", VALID_EXAMPLES)
def test_examples_compile_and_match_expected_output(name):
    source = (EXAMPLES_DIR / name).read_text(encoding="utf-8")
    expected = (EXAMPLES_DIR / "expected" / name.replace(".cb", ".txt")).read_text(encoding="utf-8")
    assert run_ast(source) == expected
    result = compile_source(source)
    assert result.success
    assert run_tac(result.optimized_tac) == expected
    assert build_and_run_cpp(result.cpp) == expected


@needs_cxx
def test_unoptimized_cpp_matches_too():
    source = (EXAMPLES_DIR / "primes.cb").read_text(encoding="utf-8")
    assert build_and_run_cpp(cpp_for(source, optimized=False)) == run_ast(source)


@needs_cxx
def test_random_programs_compile_and_match():
    rng = random.Random(7)
    sources, expected = [], []
    while len(sources) < 12:
        src = _random_program(rng)
        try:
            out = run_ast(src)
        except RuntimeFault:
            continue
        sources.append(src)
        expected.append(out)
    for src, out in zip(sources, expected):
        assert build_and_run_cpp(cpp_for(src)) == out, src


@needs_cxx
def test_semantics_edge_cases_match_cpp():
    source = """
let a = -7
let b = 2
print(a / b, a % b, a / -b, a % -b)
let f = 0.1 + 0.2
print(f, 1.0 / 3.0, 1e20, 123456789.0, 2.5e-7)
let s = "tab\\tquote\\"slash\\\\"
print(s, s + "!", s == "x", true, not true)
let x = 5
let ok = x > 3 and x < 10 or x == 0
print(ok, -x, - -x, 0.5 * x)
"""
    expected = run_ast(source)
    assert build_and_run_cpp(cpp_for(source)) == expected
    assert build_and_run_cpp(cpp_for(source, optimized=False)) == expected
