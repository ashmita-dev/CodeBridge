import random

import pytest

from app.compiler.codegen_cpp import cpp_string, generate_cpp
from app.compiler.optimizer import optimize
from app.compiler.pipeline import compile_source
from app.compiler.tac import BinOp, Const, Copy, Goto, IfFalse, Label, Print, Var
